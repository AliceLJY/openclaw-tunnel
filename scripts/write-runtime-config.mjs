#!/usr/bin/env node

import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(process.env.OPENCLAW_TUNNEL_ROOT || path.join(scriptDir, '..'));
const runtimeDir = path.join(repoRoot, '.runtime');
const envPath = path.join(repoRoot, '.env');
const runnerEnvPath = path.join(runtimeDir, 'runner.env');
const pluginConfigPath = path.join(runtimeDir, 'openclaw-plugin-config.json');

function value(name, fallback = '') {
  return process.env[name] ?? fallback;
}

function requireValue(name) {
  const result = value(name).trim();
  if (!result) throw new Error(`${name} is required`);
  return result;
}

function dotenvQuote(input) {
  const text = String(input);
  if (text.includes('\n') || text.includes('\r') || text.includes('\0')) {
    throw new Error('runtime configuration values must be single-line strings');
  }
  return `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function writePrivateFile(filePath, content) {
  fs.writeFileSync(filePath, content, { encoding: 'utf8', mode: 0o600 });
  fs.chmodSync(filePath, 0o600);
}

function main() {
  const port = value('PORT', '3456').trim();
  const portNumber = Number.parseInt(port, 10);
  if (!/^\d+$/.test(port) || portNumber < 1 || portNumber > 65535) {
    throw new Error('PORT must be an integer between 1 and 65535');
  }

  const callbackBotToken = requireValue('CALLBACK_BOT_TOKEN');
  const callbackChannel = value('CALLBACK_CHANNEL').trim();
  const workerToken = randomBytes(32).toString('hex');
  const taskApiBind = value('TASK_API_BIND', '127.0.0.1').trim() || '127.0.0.1';
  const workerUrl = value('WORKER_URL', `http://127.0.0.1:${port}`).trim();
  const pluginApiUrl = value('PLUGIN_API_URL', `http://host.docker.internal:${port}`).trim();

  const taskApiEnvValues = {
    WORKER_TOKEN: workerToken,
    PORT: port,
    TASK_API_BIND: taskApiBind,
    CALLBACK_BOT_TOKEN: callbackBotToken,
    CALLBACK_API_BASE_URL: value('CALLBACK_API_BASE_URL', 'https://discord.com/api/v10'),
    CALLBACK_CHANNEL: callbackChannel,
  };
  const runnerEnvValues = {
    WORKER_TOKEN: workerToken,
    WORKER_URL: workerUrl,
    CLAUDE_PATH: value('CLAUDE_PATH', 'claude'),
    CODEX_PATH: value('CODEX_PATH', 'codex'),
    GEMINI_PATH: value('GEMINI_PATH', 'gemini'),
    CC_TIMEOUT: value('CC_TIMEOUT', '1200000'),
    CC_MODELS: value('CC_MODELS'),
    RUNNER_SESSION_CACHE_FILE: value('RUNNER_SESSION_CACHE_FILE'),
    CC_LOG_PATH: value('CC_LOG_PATH'),
    WORKER_DIRECT_CALLBACK: value('WORKER_DIRECT_CALLBACK', 'false'),
  };

  const taskApiEnvContent = [
    '# Generated by setup.sh. Private task-api credentials; do not commit or share.',
    '',
    '# === task-api (runs in Docker) ===',
    ...Object.entries(taskApiEnvValues)
      .map(([key, entryValue]) => `${key}=${dotenvQuote(entryValue)}`),
    '',
  ].join('\n');

  const runnerEnvContent = [
    '# Generated by setup.sh. Private runner credentials; do not commit or share.',
    '',
    '# === runner (runs on host) ===',
    ...Object.entries(runnerEnvValues)
      .map(([key, entryValue]) => `${key}=${dotenvQuote(entryValue)}`),
    '',
  ].join('\n');

  const pluginConfig = {
    plugins: {
      entries: {
        'cli-bridge': {
          enabled: true,
          config: {
            apiUrl: pluginApiUrl,
            apiToken: workerToken,
            callbackChannel,
          },
        },
      },
    },
  };

  fs.mkdirSync(runtimeDir, { recursive: true, mode: 0o700 });
  fs.chmodSync(runtimeDir, 0o700);
  writePrivateFile(envPath, taskApiEnvContent);
  writePrivateFile(runnerEnvPath, runnerEnvContent);
  writePrivateFile(pluginConfigPath, `${JSON.stringify(pluginConfig, null, 2)}\n`);
}

try {
  main();
} catch (error) {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`Runtime config generation failed: ${message}`);
  process.exitCode = 1;
}
